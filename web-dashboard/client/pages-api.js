// GitHub Pages has no server. Public scripts run in an opaque sandbox; holdings
// never enter these requests. Failed sources fall back to dated public snapshots.
import {INDICES,parseQuotes,parseFlows,number,chinaDate,stockCode,marketClock} from '../worker/data.js';
const memo=new Map(),pending=new Map(),files=new Map();
const fail=message=>{throw Error(message);};
export function snapshotValue(value,now=Date.now()) {
  if(!value)return null;
  return {...value,delivery:'github-snapshot',stale:!!value.stale||!value.fetched_at||now-Date.parse(value.fetched_at)>900000};
}
export function subset(value,codes) {
  if(!value)return null;
  const items=codes.map(code=>value.items?.find(r=>r.code===code)).filter(Boolean);
  return items.length?{...value,items,missing:codes.filter(code=>!items.some(r=>r.code===code))}:null;
}
async function file(name,ttl=30000) {
  const hit=files.get(name);if(hit&&Date.now()-hit.saved<ttl)return hit.value;
  const response=await fetch(new URL('./data/'+name+'.json',document.baseURI),{cache:'no-cache',signal:AbortSignal.timeout(12000)});
  if(!response.ok)throw Error('GitHub 公共快照暂不可用');
  const value=await response.json();files.set(name,{saved:Date.now(),value});return value;
}
function bridge(kind,params={}) {
  return new Promise((resolve,reject)=>{
    const nonce=crypto.randomUUID(),frame=document.createElement('iframe');frame.hidden=true;frame.setAttribute('sandbox','allow-scripts');
    frame.src=new URL('./bridge.html',document.baseURI).href+'#'+encodeURIComponent(JSON.stringify({kind,nonce,...params}));
    const done=(error,value)=>{clearTimeout(timer);window.removeEventListener('message',receive);frame.remove();error?reject(Error(error)):resolve(value);};
    const receive=event=>{if(event.source===frame.contentWindow&&event.data?.kind==='public-market'&&event.data.nonce===nonce)done(event.data.error,event.data.value);};
    const timer=setTimeout(()=>done('浏览器直连公开来源超时'),8000);window.addEventListener('message',receive);document.body.append(frame);
  });
}
export function parseMinute(payload,code) {
  const b=payload?.data?.[code],rows=b?.data?.data;if(!rows?.length)fail('暂无分时数据');
  const raw=String(b.data.date||''),date=/^\d{8}$/.test(raw)?raw.slice(0,4)+'-'+raw.slice(4,6)+'-'+raw.slice(6):raw||null;
  return {code,date,points:rows.map(row=>{const a=row.split(' ');return {time:a[0].slice(0,2)+':'+a[0].slice(2),price:number(a[1]),volume:number(a[2]),turnover_yuan:number(a[3])};}).filter(p=>p.price!==null),previous_close:number(b.qt?.[code]?.[4]),source:'腾讯财经 · 实际分时点'};
}
export function parseFundArchive(raw,code) {
  const points=(raw?.trend||[]).map(r=>({date:chinaDate(r.x),nav:number(r.y),pct:number(r.equityReturn)})).filter(r=>r.nav>0);
  if(!points.length)fail('暂无基金历史净值');
  return {code,name:raw.name,points,history_scope:'all',fees:raw.fees?Object.fromEntries(Object.entries(raw.fees).map(([k,v])=>[k,number(v)])):null,managers:(raw.managers||[]).map(m=>({name:m.name,experience:m.workTime})),allocation:raw.allocation?{date:raw.allocation.categories?.at(-1),items:raw.allocation.series?.map(r=>({name:r.name,value:number(r.data?.at(-1))}))}:null,scale:raw.scale?{date:raw.scale.categories?.at(-1),value:number(raw.scale.series?.at(-1)?.y)}:null,holdings:(raw.holdings||[]).map(c=>c.startsWith('1.')?'sh'+c.slice(2):c.startsWith('0.')?'sz'+c.slice(2):null).filter(Boolean),as_of:points.at(-1).date,source:'天天基金 · 历史单位净值 / 披露重仓股'};
}
async function live(path,query) {
  const code=query.get('code');
  if(path==='/api/indices'||path==='/api/quotes'){
    const codes=path==='/api/indices'?INDICES:(query.get('codes')||'').split(',').map(stockCode).slice(0,40);
    const items=parseQuotes(await bridge('quotes',{codes}));if(!items.length)fail('暂无有效行情');
    return {items,missing:codes.filter(c=>!items.some(r=>r.code===c)),source:'腾讯财经',clock:marketClock()};
  }
  if(path==='/api/minute')return parseMinute(await bridge('minute',{code:stockCode(code)}),stockCode(code));
  if(path==='/api/daily'){
    const clean=stockCode(code),payload=await bridge('daily',{code:clean}),b=payload?.data?.[clean],rows=b?.qfqday||b?.day;
    if(!rows?.length)fail('暂无日线数据');
    return {code:clean,points:rows.map(a=>({date:a[0],open:number(a[1]),close:number(a[2]),high:number(a[3]),low:number(a[4]),volume:number(a[5])})),source:'腾讯财经 · 前复权日线'};
  }
  if(path==='/api/flows'){
    const period=query.get('period')||'intraday',payload=await bridge('flow',{code:code==='market'?'market':stockCode(code),period}),points=parseFlows(payload?.data?.klines).slice(period==='history'?-30:-300);
    if(!points.length)fail('公开资金曲线暂不可用');
    return {code,points,as_of:points.at(-1).time,unit:'亿元',source:'东方财富 · 资金流',method:'按数据源的买卖方向与订单规模划分；主力=超大单+大单。净流入是交易分类统计，并非市场新增现金。'};
  }
  if(path==='/api/fund-history'){
    if(!/^\d{6}$/.test(code))fail('无效基金代码');
    return parseFundArchive(await bridge('fund-history',{code}),code);
  }
  // Industry tables, fund estimates and VIX are generated by GitHub Actions.
  fail('该数据使用 GitHub Actions 公共快照');
}
async function snapshot(path,query) {
  const data=await file('snapshot'),routes=data.routes||{};
  if(path==='/api/fund-directory')return snapshotValue(await file('fund-directory',86400000));
  if(path==='/api/fund-rankings')return snapshotValue(await file('fund-navs',300000));
  if(path==='/api/funds'){
    const codes=(query.get('codes')||'').split(',').filter(Boolean);
    if(!codes.length||codes.length>60||codes.some(c=>!/^\d{6}$/.test(c)))fail('最多查询60只六位基金代码');
    let navs;try{navs=await file('fund-navs',300000);}catch{}
    const selected=routes['/api/funds'];
    const items=codes.map(code=>{const a=selected?.items.find(r=>r.code===code),b=navs?.items.find(r=>r.code===code);return a&&(!b||a.date>=b.date)?a:b;}).filter(Boolean);
    const missing=codes.filter(c=>!items.some(r=>r.code===c));
    // New funds absent from the published ranking can still use their public archive.
    const histories=await Promise.allSettled(missing.map(code=>publicApi('/api/fund-history?code='+code)));
    histories.forEach((result,i)=>{if(result.status==='fulfilled'){const h=result.value,p=h.points.at(-1);items.push({code:missing[i],name:h.name||missing[i],date:p.date,nav:p.nav,pct:p.pct,source:'已公布净值 · 基金档案'});}});
    if(!items.length)fail('该代码暂无有效基金数据');
    return snapshotValue({items,missing:codes.filter(c=>!items.some(r=>r.code===c)),warnings:selected?.warnings||[],source:'天天基金 / 东方财富',fetched_at:[selected?.fetched_at,navs?.fetched_at].filter(Boolean).sort()[0],stale:!!selected?.stale});
  }
  if(path==='/api/search-funds'){
    const directory=await file('fund-directory',86400000),q=(query.get('q')||'').trim().toLowerCase();
    return snapshotValue({...directory,items:directory.items.filter(r=>r.code.includes(q)||r.name.toLowerCase().includes(q)||r.pinyin?.toLowerCase().includes(q)).slice(0,20)});
  }
  if(path==='/api/quotes'){
    const combined=[routes['/api/indices'],routes['/api/quotes']].filter(Boolean);
    return snapshotValue(subset({items:combined.flatMap(d=>d.items),source:'腾讯财经',fetched_at:combined.map(d=>d.fetched_at).sort()[0]},(query.get('codes')||'').split(',').map(stockCode)));
  }
  const key=path+(['flows','minute','daily','fund-history'].some(s=>path.endsWith('/'+s))?'?code='+query.get('code')+(path.endsWith('/flows')?'&period='+(query.get('period')||'intraday'):''):'');
  return snapshotValue(routes[key]);
}
export async function publicApi(input) {
  const url=new URL(input,'https://public.invalid'),path=url.pathname,query=url.searchParams;
  if(path==='/api/health')return {clock:marketClock(),source:'GitHub Pages',fetched_at:new Date().toISOString()};
  const key=path+'?'+query,hit=memo.get(key);
  if(hit&&Date.now()-hit.saved<20000)return hit.value;
  if(pending.has(key))return pending.get(key);
  const work=(async()=>{
    if(['/api/fund-directory','/api/fund-rankings','/api/funds','/api/search-funds','/api/sectors','/api/vix'].includes(path))return snapshot(path,query);
    const direct=live(path,query).then(value=>{const result={...value,fetched_at:new Date().toISOString(),delivery:'browser',stale:false};memo.set(key,{saved:Date.now(),value:result});return result;});
    // Fast first paint from a dated snapshot while direct loading continues.
    const fallback=snapshot(path,query).catch(()=>null);
    const first=await Promise.race([direct.catch(()=>null),new Promise(resolve=>setTimeout(()=>resolve(null),700))]);
    if(first)return first;
    const saved=await fallback;
    if(saved){direct.catch(()=>{});return saved;}
    return direct;
  })().finally(()=>pending.delete(key));pending.set(key,work);return work;
}
